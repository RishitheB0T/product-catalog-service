-- BUILD FLOW 04.01 — V1__create_product_table.sql
-- First introduced: Phase 04
-- Purpose: Creates the product table, the single source of truth for the catalog, together with the
--          rules the database itself enforces. Flyway owns the schema; Hibernate only validates it.
-- Depends on: MySQL 8.4 (CHECK constraints need 8.0.16+, expression defaults 8.0.13+).
-- Used by: Flyway at application startup and in every database test, before Hibernate starts.
-- Runtime role: Runs exactly once per database. Flyway records it in flyway_schema_history with a checksum,
--               so editing this file after it has run makes Flyway refuse to start. Later changes go into
--               new files: V2__..., V3__...
--
-- File name format: V<version>__<description>.sql, with TWO underscores after the version.
-- Deliberately no search indexes yet: Phase 08 measures the queries first and adds indexes in a new migration.

-- BUILD FLOW 04.01.01 — Columns
CREATE TABLE product (
    -- Surrogate key: a number with no business meaning, generated by MySQL on insert. BIGINT instead of INT
    -- leaves room for far more than 2.1 billion rows.
    id             BIGINT         NOT NULL AUTO_INCREMENT,
    -- Business key: the stock-keeping unit, unique per product (constraints below).
    sku            VARCHAR(32)    NOT NULL,
    name           VARCHAR(120)   NOT NULL,
    description    VARCHAR(2000)  NOT NULL,
    -- Stored as text matching the Java enum Category; the CHECK constraint below lists the allowed values.
    category       VARCHAR(32)    NOT NULL,
    -- DECIMAL(10,2): exact decimal arithmetic for money, up to 99,999,999.99 rupees. FLOAT and DOUBLE store
    -- binary fractions and would round amounts such as 0.10.
    price          DECIMAL(10, 2) NOT NULL,
    stock_quantity INT            NOT NULL,
    -- Optional: the storefront shows a fallback picture when it is missing.
    image_url      VARCHAR(500)   NULL,
    -- UTC timestamps with microsecond precision. DATETIME instead of TIMESTAMP because TIMESTAMP ends on
    -- 2038-01-19. The application always sets both values; the defaults only serve SQL seed scripts.
    created_at     DATETIME(6)    NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    updated_at     DATETIME(6)    NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    -- Optimistic-locking counter: every successful update increments it (Hibernate's @Version), so an update
    -- based on an outdated copy can be detected and rejected instead of silently overwriting newer data.
    version        BIGINT         NOT NULL DEFAULT 0,

    -- MySQL always names the primary key "PRIMARY"; the index on it is the clustered index that stores the rows.
    PRIMARY KEY (id),

    -- BUILD FLOW 04.01.02 — Rules the database enforces, whatever the client
    -- Named constraints produce readable error messages, which the API translates in Phase 05.
    CONSTRAINT uk_product_sku UNIQUE (sku),
    -- Upper-case letters, digits, and hyphens, starting with a letter or digit. Match type 'c' makes the
    -- regular expression case-sensitive (the column's collation is case-insensitive).
    CONSTRAINT ck_product_sku_format CHECK (REGEXP_LIKE(sku, '^[A-Z0-9][A-Z0-9-]*$', 'c')),
    CONSTRAINT ck_product_name_not_blank CHECK (CHAR_LENGTH(TRIM(name)) > 0),
    CONSTRAINT ck_product_description_not_blank CHECK (CHAR_LENGTH(TRIM(description)) > 0),
    CONSTRAINT ck_product_category CHECK (category IN ('APPAREL', 'FOOTWEAR', 'BAGS', 'HOME', 'KITCHEN', 'STATIONERY')),
    CONSTRAINT ck_product_price_not_negative CHECK (price >= 0),
    CONSTRAINT ck_product_stock_not_negative CHECK (stock_quantity >= 0)
)
-- InnoDB: transactions, row locks, and foreign keys. utf8mb4 stores every Unicode character (including
-- emoji); utf8mb4_0900_ai_ci compares text ignoring accents and case, so a search for "linen" finds "Linen".
ENGINE = InnoDB
DEFAULT CHARSET = utf8mb4
COLLATE = utf8mb4_0900_ai_ci;
